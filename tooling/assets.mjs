import {readdir,readFile,writeFile} from 'node:fs/promises';
import {extname} from 'node:path';
const assets={};
for(const path of await readdir('dist/web',{recursive:true})){if(!extname(path))continue;const type={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8'}[extname(path)];if(type)assets['/'+path]={body:await readFile('dist/web/'+path,'utf8'),type};}
await writeFile('apps/api/src/assets.generated.ts','// Generated by tooling/assets.mjs\nexport const assets:Record<string,{body:string,type:string}>='+JSON.stringify(assets)+';\n');
